// 오늘 날짜 기준으로 단원 하나를 고름 (매일 순환)
export function todaysUnit(grade, subject) {
  const list = UNITS[grade]?.[subject] || [];
  if (list.length === 0) return "종합";
  const epochDays = Math.floor(Date.now() / (1000 * 60 * 60 * 24));
  return list[epochDays % list.length];
}

